function tagsFor(slug: string, stateSectors: string[]): string[] {
  const local: Record<string, string[]> = {
    jaipur: ["heritage tourism", "gems & jewellery", "education hubs", "IT parks", "government campuses"],
    mumbai: ["BFSI", "corporate HQs", "ports & logistics", "high-rise residential", "retail malls"],
    pune: ["auto & EV", "IT parks", "education", "manufacturing", "warehousing"],
    bengaluru: ["IT / GCCs", "startups", "biotech", "data centres", "residential townships"],
    hyderabad: ["IT", "pharma", "life sciences", "warehousing", "hospitals"],
    chennai: ["auto", "IT", "ports", "electronics", "hospitals"],
    kolkata: ["ports", "IT/ITES", "hospitals", "retail", "manufacturing"],
    ahmedabad: ["textiles", "pharma", "commercial complexes", "warehousing", "SEZ units"],
    surat: ["diamonds", "textiles", "logistics", "retail"],
    delhi: ["corporate offices", "embassies", "malls", "hospitals", "events"],
    "new-delhi": ["corporate offices", "government", "malls", "hospitals", "events"],
    gurugram: ["IT/ITES", "corporate campuses", "warehousing", "residential societies", "hospitals"],
    noida: ["IT parks", "electronics", "warehousing", "residential", "industrial"],
    lucknow: ["government", "education", "hospitals", "retail", "residential"],
    indore: ["manufacturing", "commercial", "education", "warehousing"],
    bhopal: ["government", "education", "industrial", "hospitals"],
  };
  if (local[slug]) return local[slug];
  return stateSectors.slice(0, 5);
}

function buildCities(): CityInfo[] {
  const cities: CityInfo[] = [];
  const seen = new Set<string>();
  for (const st of STATES) {
    for (const slug of st.cities) {
      if (seen.has(slug)) continue;
      seen.add(slug);
      cities.push({
        slug,
        name: NAME_MAP[slug] || slug.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
        stateSlug: st.slug,
        stateName: st.name,
        tier: TIER1.has(slug) ? 1 : TIER2.has(slug) ? 2 : 3,
        economyTags: tagsFor(slug, st.sectors),
      });
    }
  }
  return cities;
}

export const CITIES = buildCities();

export function getCity(slug: string) {
  return CITIES.find((c) => c.slug === slug);
}

export function citiesInState(stateSlug: string) {
  return CITIES.filter((c) => c.stateSlug === stateSlug);
}
